def build_angle_prompt(req: GenerateRequest, snippets: list[str] | None = None) -> list[dict]:
    """阶段一：审题立意（低温度，输出结构化候选立意）。"""
    system = (
        f"{_ROLE}\n\n"
        "当前任务是【审题立意】，不要写正文。你的产出会被下游的提纲阶段直接使用，"
        "所以要具体、可落地，不要空泛。"
    )
    user = f"""\
{_topic_block(req)}

{_materials_block(snippets or [])}
请完成审题立意，严格按下面格式输出（不要写任何额外说明、不要写正文）：

【题目类型】命题作文/材料作文/任务驱动型/话题作文 之一，并用一句话说明判断依据。
【核心概念】把题目拆成 1~3 个必须辨析的关键词，各用一句话界定其内涵与易混淆处。
【价值取向】本题在考查哪种价值取向（如家国情怀、独立思考、文化自信、奋斗进取、平视世界），一句话说明。
【候选立意】（共 {req.angle_count} 个，按推荐度排序，每个不超过 60 字）
立意1：…
立意2：…
立意3：…（若只要 2 个则省略此行）
【推荐立意】直接给出你要写的那个立意，用一句话说清“从什么切入、论证什么、落到什么”。
【标题备选】（3 个，各 8~14 字，风格各不相同：意象型 / 判断型 / 化用型）
【可能踩的坑】本题最容易写崩的 2 个方向，各一句话。
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def build_outline_prompt(req: GenerateRequest, angle: str) -> list[dict]:
    """阶段二：结构提纲（把立意变成可执行骨架）。"""
    system = (
        f"{_ROLE}\n\n"
        "当前任务是【结构提纲】，不要写正文。提纲要细到每一段写什么、用哪个论据、"
        "分析句往哪个方向走，让下游写作阶段可以“照着填肉”。"
    )
    user = f"""\
{_topic_block(req)}

【上游审题立意结果】
{angle.strip()}

{_PATTERNS}
请输出提纲，严格按下面格式：

【选定标题】从上游标题备选中选一个（或按同风格重写一个），8~14 字。
【中心论点】一句话，不超过 30 字，必须是可被反驳的判断句，不是口号。
【分论点】
分论点一：观点句（≤25字）｜论据：具体人事/典籍/现象（≤40字）｜分析方向：由果溯因 or 假设对比（≤30字）
分论点二：同上
分论点三：同上（三个分论点之间必须是递进关系，不是并列堆叠）
【让步段】要承认的对立面是什么、转折后落到什么（≤60字）
【结尾升维路径】从（个体/一事）→（时代/民族/文明）的具体路径（≤50字）
【预计字数分配】首段__字 / 主体三段各__字 / 让步段__字 / 结尾__字
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def build_essay_prompt(req: GenerateRequest, outline: str, snippets: list[str] | None = None) -> list[dict]:
    """阶段三：正文成篇（高温度，流式输出全文）。"""
    system = (
        f"{_ROLE}\n\n"
        "当前任务是【正文成篇】。你现在不是在“回答问题”，而是在考场里写一篇要拿 50 分以上的作文。\n\n"
        f"{_PATTERNS}\n{_STYLE}\n{_NEGATIVE}\n"
        "【输出格式（严格遵守）】\n"
        "第一行：标题：<你的标题>（不带书名号，也不要写多余的字）\n"
        "第二行：空行\n"
        "之后是正文，逐段输出，段与段之间空一行，段落开头不空格、不使用任何符号标记。\n"
        "只输出这些内容，不要写“正文如下”“以上”之类的话，不要在文末做任何总结或自评。"
    )
    user = f"""\
{_topic_block(req)}

【已确定的提纲（必须执行，但允许在细节上比提纲更精彩）】
{outline.strip()}

{_materials_block(snippets or [])}
现在开始写。注意：
- 一次写完整篇，不要中途停笔，不要分段请求确认。
- 严格控制在 {req.word_count} 字左右，宁可少 30 字也不要超出 120 字。
- 结尾必须写完，最后一个字必须是句号或问号。
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def build_critique_prompt(req: GenerateRequest, essay: str) -> list[dict]:
    """阶段四：评分自检（低温度，强制 JSON）。"""
    system = (
        f"{_ROLE}\n\n"
        "当前任务是【评分自检】。你要像真实阅卷一样严格：一类卷名额有限，"
        "不要因为文从字顺就给高分，要盯住“立意是否独到、思辨是否真实、语言是否有个人印记”。\n"
        "只输出一个 JSON 对象，不要输出 Markdown 代码块标记，不要输出任何解释文字。"
    )
    user = f"""\
{_topic_block(req)}

【待评作文】
{essay.strip()}

请按高考 60 分制评分，并严格输出如下 JSON（字段齐全，数值为数字，不得使用字符串）：

{{
  "total": 0-60 之间的数字，保留一位小数,
  "base": {{"content": 0-20 的数字, "expression": 0-20 的数字}},
  "development": {{"deep": 0-5, "rich": 0-5, "literary": 0-5, "creative": 0-5}},
  "verdict": "一类上/一类下/二类上/二类下/三类 之一",
  "highlights": ["亮点1（要引原文片段）", "亮点2", "亮点3"],
  "flaws": ["硬伤1（指出具体位置与原因）", "硬伤2"],
  "suggestions": ["可执行的修改建议1", "建议2", "建议3"],
  "comment": "60~100 字的阅卷评语"
}}

评分口径提醒：base.content + base.expression 不得超过 40；development 四项各不超过 5；
total 应约等于 base 之和 + development 之和，允许 ±1 的浮动。
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def build_polish_prompt(req: GenerateRequest, essay: str, critique: str) -> list[dict]:
    """阶段五：润色定稿（中温度，带着硬伤清单重写）。"""
    system = (
        f"{_ROLE}\n\n"
        "当前任务是【润色定稿】。你手里有一篇初稿和一份阅卷意见，"
        "请按意见修订：优先修掉硬伤，再提升语言的个人印记，最后检查结尾是否有余味。"
        "修订不是重写——保留初稿中所有已经出彩的句子。\n\n"
        f"{_NEGATIVE}\n"
        "【输出格式】与初稿一致：第一行“标题：…”，空行，然后正文。只输出稿件本身。"
    )
    user = f"""\
{_topic_block(req)}

【初稿】
{essay.strip()}

【阅卷意见（JSON）】
{critique.strip()}

请输出修订后的定稿。要求：
- 修正阅卷意见中 flaws 列出的每一处硬伤；
- 至少落实两条 suggestions；
- 保持 {req.word_count} 字左右，结尾完整；
- 不要在文末附修改说明。
"""
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


# --------------------------------------------------------------------------
# 四、给 /api/prompts 的结构化导出（前端“提示词”页 + 实验报告用）
# --------------------------------------------------------------------------

def _specs() -> list[dict]:
    """用一份示例请求把真实提示词渲染出来，供前端/报告展示。"""
    demo = GenerateRequest(
        topic="以“守正与创新”为题，写一篇不少于 800 字的议论文",
        material="《论语》讲“温故而知新”，《周易》讲“穷则变，变则通”。",
        requirement="自选角度，自拟标题；不要套作，不得抄袭；不少于 800 字。",
        genre="议论文",
        word_count=800,
        angle_count=3,
        do_critique=True,
    )
    stages = [
        ("angle", build_angle_prompt(demo)),
        ("outline", build_outline_prompt(demo, "（上游审题立意结果）")),
        ("essay", build_essay_prompt(demo, "（上游提纲）")),
        ("critique", build_critique_prompt(demo, "（初稿正文）")),
        ("polish", build_polish_prompt(demo, "（初稿正文）", "（评分 JSON）")),
    ]
    out = []
    for key, messages in stages:
        system = next((m["content"] for m in messages if m["role"] == "system"), "")
        user = next((m["content"] for m in messages if m["role"] == "user"), "")
        out.append(
            {
                "key": key,
                "title": STAGE_TITLES[key],
                "system": system,
                "user_template": user,
            }
        )
    return out


PROMPT_SPECS: list[dict] = _specs()

