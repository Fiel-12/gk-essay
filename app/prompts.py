# 从 20 份满分范文归纳出的结构规律（写成可执行规则，而不是空泛要求）
_PATTERNS = """\
【一类卷结构范式（从 20 份满分范文中归纳，请严格遵循）】
1. 标题：8~14 字，意象对举 / 比喻 / 化用诗文，必须含题目关键词的近义表达；
   禁用“浅谈…”“…之我见”“论…”这类平庸结构。
2. 首段（80~120 字，3 句以内）：用排比、设问、场景或引语切入，
   末句必须出现立意关键词（点题），不允许铺垫超过 3 句。
3. 主体（3 段，每段 150~200 字）：每段第一句是观点句（不用“首先/其次”），
   随后至少两类论据（人物事件 / 典籍引文 / 数据现象），
   论据之后必须有一句“由果溯因”或“假设对比”的分析句，最后一句回扣题目。
4. 让步段（1 段，100~130 字）：放在结尾前，先承认对立面的合理处（“诚然…”），
   再用“然而/但”转折，体现思辨，禁止写成两面讨好。
5. 结尾（不超过 120 字）：由个体升维到时代、民族或人类文明，回扣标题意象，
   最后一句留有余味；禁止“综上所述”“总之”“让我们一起”。
6. 语言：全文至少两处引用古诗文或典籍原文（要准确，宁可少不可错）；
   长短句比例约 3:7；四字短语点缀而不铺满。
"""

_NEGATIVE = """\
【黑名单（出现即视为硬伤，一律不许写）】
- 开头套话：“在当今社会”“随着…的发展”“不可否认”“这无疑”“众所周知”
- 结尾套话：“综上所述”“总而言之”“让我们一起”“作为新时代青年，我们要”
- 网络/职场词：“赋能”“闭环”“流量”“内卷”“破防”“抓手”“赛道”
- 结构符号：小标题、序号、“第一…第二…第三…”、项目符号
- 排比通胀：连续排比不超过 2 组，每组必须更换意象，不许同义反复
- 论据烂大街：屈原投江、司马迁宫刑、爱迪生、居里夫人、感动中国人物堆砌
  （整篇最多出现一处，且必须给出新解读）
- 空洞口号：通篇大词而无具体人事，读后不记得任何一个细节
- 自我暴露：不得出现“作为 AI”“以下是一篇”“我将为你”等元话语
"""

_STYLE = """\
【语言质地要求】
- 具象优先：能写“青铜器上的绿锈”就不写“悠久的历史”。
- 引用要“化”不要“贴”：引文后面必须跟一句自己的解释或推进。
- 每 200 字至少出现一处让阅卷老师抬头的表达（比喻、通感、反常合道的判断）。
- 句式有呼吸：长句铺陈之后用 4~8 字的短句收束。
"""


def _topic_block(req: GenerateRequest) -> str:
    parts = [f"【作文题目】\n{req.topic.strip()}"]
    if req.material.strip():
        parts.append(f"【材料/引言】\n{req.material.strip()}")
    if req.requirement.strip():
        parts.append(f"【写作要求】\n{req.requirement.strip()}")
    parts.append(f"【文体】{req.genre}：{GENRES.get(req.genre, GENRES['议论文'])}")
    parts.append(f"【目标字数】{req.word_count} 字（允许 ±8%，但结尾必须完整）")
    return "\n\n".join(parts)


def _materials_block(snippets: list[str]) -> str:
    if not snippets:
        return ""
    body = "\n".join(f"- {s.strip()[:320]}" for s in snippets if s.strip())
    if not body:
        return ""
    return (
        "【本地范文库检索到的可参考素材（只可借鉴立意角度与句式，严禁整段照抄）】\n"
        f"{body}\n"
    )


